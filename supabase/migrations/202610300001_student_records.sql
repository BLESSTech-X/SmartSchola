-- SmartSchola student records module
-- Extends the tenant-scoped student table to support the existing school register UI.
-- RLS policies from the initial tenant migration remain in force.

alter table public.students
  add column if not exists grade text not null default '',
  add column if not exists class_name text not null default '',
  add column if not exists gender text,
  add column if not exists parent_phone text,
  add column if not exists address text;

alter table public.students
  alter column student_number set default (
    'STU-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  );

alter table public.students
  add constraint students_gender_check
  check (gender is null or gender in ('Male', 'Female', 'Other'))
  not valid;

create index if not exists students_school_name_idx
  on public.students (school_id, last_name, first_name);

create index if not exists students_school_status_idx
  on public.students (school_id, status);

comment on column public.students.student_number is
  'School-unique student reference; generated by default when not supplied.';
comment on column public.students.class_name is
  'Display class label retained for register compatibility; class_id can link to the structured classes table.';
